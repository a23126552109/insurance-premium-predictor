DESC TABLE
INSURANCE_ML_DB.INSURANCE_SCHEMA.AUTOMATED_INSURANCE_PREDICTIONS;

CREATE OR REPLACE PROCEDURE
INSURANCE_ML_DB.INSURANCE_SCHEMA.PROCESS_INSURANCE_CUSTOMERS()

RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER

AS
$$
BEGIN

    INSERT INTO
    INSURANCE_ML_DB.INSURANCE_SCHEMA.AUTOMATED_INSURANCE_PREDICTIONS
    (
        AGE,
        SEX,
        BMI,
        CHILDREN,
        SMOKER,
        REGION,
        PREDICTED_CHARGES,
        PREDICTION_DATE
    )

    SELECT
        s.AGE,
        s.SEX,
        s.BMI,
        s.CHILDREN,
        s.SMOKER,
        s.REGION,

        (
            INSURANCE_ML_DB.INSURANCE_SCHEMA
            .INSURANCE_CHARGES_XGB!PREDICT(
                s.AGE,
                s.SEX,
                s.BMI,
                s.CHILDREN,
                s.SMOKER,
                s.REGION
            )
        ):"output_feature_0"::FLOAT,

        CURRENT_TIMESTAMP()::TIMESTAMP_NTZ

    FROM
    INSURANCE_ML_DB.INSURANCE_SCHEMA.INSURANCE_CUSTOMER_STREAM s

    WHERE
        s.METADATA$ACTION = 'INSERT'
        AND s.METADATA$ISUPDATE = FALSE;

    RETURN 'Insurance customer predictions processed successfully';

END;
$$;

CALL INSURANCE_ML_DB.INSURANCE_SCHEMA.PROCESS_INSURANCE_CUSTOMERS();

